// Contrast of every text/background colour token pair in both themes, from
// src/styles/tokens.css, by the WCAG 2.2 relative luminance formula.
//
//   node scripts/contrast.mjs                         print the table, exit 1 if a pair is under 4.5:1
//   node scripts/contrast.mjs --write docs/contrast.md  also write the table there
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

export const TOKENS_FILE = fileURLToPath(new URL("../src/styles/tokens.css", import.meta.url));
export const MIN_RATIO = 4.5;

/** Text colours, each checked on every background. */
export const TEXT_TOKENS = ["text", "text-muted", "accent"];
export const BACKGROUND_TOKENS = ["bg", "surface", "surface-subtle"];
/** Pairs outside the grid above: [text, background]. */
export const EXTRA_PAIRS = [["on-accent", "accent"]];

/**
 * Colour tokens per theme. Light is everything declared before the
 * `prefers-color-scheme: dark` block; dark overrides it.
 * @param {string} css
 * @returns {{ light: Record<string, string>, dark: Record<string, string> }}
 */
export function parseTokens(css) {
  const split = css.search(/@media\s*\(\s*prefers-color-scheme:\s*dark\s*\)/);
  if (split < 0) throw new Error("tokens: no prefers-color-scheme: dark block");
  /** @param {string} s */
  const read = (s) => {
    /** @type {Record<string, string>} */
    const out = {};
    for (const m of s.matchAll(/--color-([a-z-]+)\s*:\s*(#[0-9a-f]{6})\b/gi)) {
      out[m[1] ?? ""] = (m[2] ?? "").toLowerCase();
    }
    return out;
  };
  const light = read(css.slice(0, split));
  return { light, dark: { ...light, ...read(css.slice(split)) } };
}

/** @param {string} hex `#rrggbb` */
export function luminance(hex) {
  const channels = [1, 3, 5].map((i) => Number.parseInt(hex.slice(i, i + 2), 16) / 255);
  const [r = 0, g = 0, b = 0] = channels.map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

/** @param {string} a @param {string} b */
export function contrastRatio(a, b) {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return ((hi ?? 0) + 0.05) / ((lo ?? 0) + 0.05);
}

/**
 * @param {{ light: Record<string, string>, dark: Record<string, string> }} themes
 * @returns {{ theme: string, text: string, background: string, fg: string, bg: string, ratio: number }[]}
 */
export function pairs(themes) {
  const list = [...TEXT_TOKENS.flatMap((t) => BACKGROUND_TOKENS.map((b) => [t, b])), ...EXTRA_PAIRS];
  return Object.entries(themes).flatMap(([theme, colours]) =>
    list.map(([text = "", background = ""]) => {
      const fg = colours[text];
      const bg = colours[background];
      if (!fg || !bg) throw new Error(`tokens: --color-${text} or --color-${background} missing (${theme})`);
      return { theme, text, background, fg, bg, ratio: contrastRatio(fg, bg) };
    }),
  );
}

/** @param {ReturnType<typeof pairs>} rows */
export function markdownTable(rows) {
  const lines = [
    "# Colour contrast",
    "",
    "Every text/background colour token pair in `src/styles/tokens.css`, in both themes, by the WCAG 2.2 contrast formula. The bar is 4.5:1 (AA, normal text). Generated by `pnpm contrast`; a test fails when this file is out of date or a pair is under the bar.",
    "",
    "| Theme | Text token | Background token | Text | Background | Ratio | AA 4.5:1 |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows.map(
      (r) =>
        `| ${r.theme} | \`--color-${r.text}\` | \`--color-${r.background}\` | \`${r.fg}\` | \`${r.bg}\` | ${r.ratio.toFixed(2)}:1 | ${r.ratio >= MIN_RATIO ? "pass" : "FAIL"} |`,
    ),
    "",
    "Borders (`--color-border`, `--color-border-strong`) are decoration, not text, and are not in this table.",
    "",
  ];
  return lines.join("\n");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rows = pairs(parseTokens(readFileSync(TOKENS_FILE, "utf8")));
  const table = markdownTable(rows);
  const target = process.argv[process.argv.indexOf("--write") + 1];
  if (process.argv.includes("--write") && target) writeFileSync(target, table);
  console.log(table);
  process.exit(rows.every((r) => r.ratio >= MIN_RATIO) ? 0 : 1);
}
